#!/usr/bin/env python3

"""
Integrate genetic cluster assignments into the
master metadata table.

This script enriches the master metadata table
with genetic cluster assignments generated by
cluster_analysis.py and creates a lightweight
metadata table for phylogenetic annotation.

Outputs
-------
- master_table_clustered.tsv
- phylogeny_metadata.tsv
"""

from pathlib import Path
import argparse
from dataclasses import dataclass

import pandas as pd

###############################################################################
# Master table columns
###############################################################################

from dataclasses import dataclass

@dataclass(frozen=True)
class MasterTableColumns:

    # Core identifiers
    TAXON: str = "Taxon"
    ACCESSION_ID: str = "Accession ID"
    VIRUS_NAME: str = "Virus name"

    # Original GISAID metadata
    HOST: str = "Host"
    COLLECTION_DATE: str = "Collection date"
    LOCATION: str = "Location"
    LINEAGE: str = "Lineage"
    GENOTYPE: str = "Genotype"

    # Derived GISAID metadata
    GISAID_COLLECTION_YEAR: str = "gisaid_collection_year"
    GISAID_COLLECTION_MONTH: str = "gisaid_collection_month"
    GISAID_EPIWEEK: str = "gisaid_epiweek"

    # Epidemiological temporal metadata
    EPIDEMIOLOGICAL_SEASON: str = "epidemiological_season"
    SEASON_EPIWEEK: str = "season_epiweek"
    SEASON_EPIWEEK_CUSTOM: str = "season_epiweek_custom"
    SEASON_WEEK: str = "season_week"

    GISAID_REGION: str = "gisaid_region"
    GISAID_COUNTRY: str = "gisaid_country"
    GISAID_DIVISION: str = "gisaid_division"
    GISAID_SUBDIVISION: str = "gisaid_subdivision"

    # Curated metadata
    AUTONOMOUS_COMMUNITY: str = "autonomous_community"
    AUTONOMOUS_COMMUNITY_CODE: str = "autonomous_community_code"
    ORIGINATING_LAB: str = "originating_lab"
    INSTITUTION: str = "institution"
    LAB_CODE_NORMALIZED: str = "lab_code_normalized"

MASTER = MasterTableColumns()

###############################################################################
# Cluster columns
###############################################################################

@dataclass(frozen=True)
class ClusterColumns:

    THRESHOLD: str = "Cluster threshold"
    CLUSTER_ID: str = "Cluster ID"
    REPRESENTATIVE: str = "Representative"
    REPRESENTATIVE_ID: str = "Representative ID"
    REPRESENTATIVE_TAXON: str = "Representative Taxon"
    CLUSTER_SIZE: str = "Cluster size"

CLUSTER = ClusterColumns()

###############################################################################
# Phylogeny annotation columns
###############################################################################

DEFAULT_PHYLOGENY_COLUMNS = [
    # Identifiers
    MASTER.TAXON,
    MASTER.ACCESSION_ID,
    MASTER.VIRUS_NAME,

    # Biological metadata
    MASTER.HOST,
    MASTER.GENOTYPE,
    MASTER.LINEAGE,

    # Temporal metadata
    MASTER.COLLECTION_DATE,
    MASTER.GISAID_COLLECTION_YEAR,
    MASTER.GISAID_COLLECTION_MONTH,
    MASTER.GISAID_EPIWEEK,
    MASTER.EPIDEMIOLOGICAL_SEASON,
    MASTER.SEASON_EPIWEEK,
    MASTER.SEASON_EPIWEEK_CUSTOM,
    MASTER.SEASON_WEEK,

    # Geographic metadata
    MASTER.GISAID_COUNTRY,
    MASTER.GISAID_DIVISION,
    MASTER.GISAID_SUBDIVISION,
    MASTER.AUTONOMOUS_COMMUNITY,

    # Laboratory metadata
    MASTER.ORIGINATING_LAB,
    MASTER.INSTITUTION,
    MASTER.LAB_CODE_NORMALIZED,
]

CLUSTER_PREFIX = "Cluster_"

###############################################################################
# Parse command-line arguments
###############################################################################

def parse_args():
    """
    Parse command-line arguments.
    """

    parser = argparse.ArgumentParser(
        description=(
            "Merge genetic cluster assignments with the "
            "master metadata table."
        )
    )

    parser.add_argument(
        "--master_table",
        required=True,
        help="Master metadata table (TSV).",
    )

    parser.add_argument(
        "--cluster_annotations",
        required=True,
        help=(
            "Cluster annotation table generated by "
            "cluster_analysis.py."
        ),
    )

    parser.add_argument(
    	"--prefix",
    	required=True,
    	help=(
    		"Prefix for output files "
    		"(e.g. RSVA, RSVB)."
    	),
    )

    parser.add_argument(
        "--outdir",
        required=True,
        help="Output directory.",
    )

    return parser.parse_args()

###############################################################################
# Read master metadata table
###############################################################################

def read_master_table(
    master_table,
):
    """
    Read master metadata table.
    """

    return pd.read_csv(
        master_table,
        sep="\t",
        low_memory=False,
    )

###############################################################################
# Read cluster annotations
###############################################################################

def read_cluster_annotations(
    cluster_annotations,
):
    """
    Read cluster annotation table.
    """

    return pd.read_csv(
        cluster_annotations,
        sep="\t",
    )

###############################################################################
# Enrich metadata
###############################################################################

def enrich_metadata(
    master_table,
):
    """
    Derive metadata fields from the original
    GISAID metadata.

    Temporal metadata includes:
    - calendar year
    - calendar month
    - ISO epidemiological week
    - epidemiological season (week 40 to week 39)
    - compact season/epiweek label

    Examples:
        2024-W40 -> 2024-25 -> W40_S24-25
        2025-W03 -> 2024-25 -> W03_S24-25
    """

    metadata = master_table.copy()

    # --------------------------------------------------------------
    # Collection date
    # --------------------------------------------------------------

    collection_date_raw = (
        metadata[MASTER.COLLECTION_DATE]
        .astype("string")
        .str.strip()
    )

    collection_date = pd.to_datetime(
        collection_date_raw,
        format="mixed",
        errors="coerce",
    )

    # --------------------------------------------------------------
    # Calendar year
    # --------------------------------------------------------------

    metadata[
        MASTER.GISAID_COLLECTION_YEAR
    ] = pd.to_numeric(
        collection_date_raw.str.extract(
            r"^(\d{4})",
            expand=False,
        ),
        errors="coerce",
    ).astype("Int64")
    

    # --------------------------------------------------------------
    # Calendar month
    # --------------------------------------------------------------

    metadata[
        MASTER.GISAID_COLLECTION_MONTH
    ] = pd.to_numeric(
        collection_date_raw.str.extract(
            r"^\d{4}-(\d{2})",
            expand=False,
        ),
        errors="coerce",
    ).astype("Int64")

    complete_date = collection_date_raw.str.match(
        r"^\d{4}-\d{2}-\d{2}$",
        na=False,
    )

    collection_date_complete = collection_date.where(
        complete_date
    )

    # --------------------------------------------------------------
    # ISO epidemiological calendar
    #
    # Use ISO year together with ISO week to correctly handle
    # dates around the beginning/end of the calendar year.
    # --------------------------------------------------------------

    iso_calendar = (
        collection_date_complete
        .dt
        .isocalendar()
    )

    iso_year = (
        iso_calendar["year"]
    )

    epiweek = (
        iso_calendar["week"]
    )

    metadata[
        MASTER.GISAID_EPIWEEK
    ] = epiweek

    # --------------------------------------------------------------
    # Epidemiological season
    #
    # SiVIRA convention:
    #
    #   Week 40 of year Y
    #       to
    #   Week 39 of year Y+1
    #
    # Examples:
    #
    #   2024-W39 -> 2023-24
    #   2024-W40 -> 2024-25
    #   2025-W03 -> 2024-25
    #   2025-W39 -> 2024-25
    #   2025-W40 -> 2025-26
    # --------------------------------------------------------------

    season_start_year = (
        iso_year.where(
            epiweek >= 40,
            iso_year - 1,
        )
    )

    season_end_year = (
        season_start_year + 1
    )

    # --------------------------------------------------------------
    # Week within epidemiological season
    #
    # Season starts at ISO week 40.
    #
    # Examples for a 52-week ISO year:
    #
    #   W40 -> 1
    #   W41 -> 2
    #   ...
    #   W52 -> 13
    #   W01 -> 14
    #   ...
    #   W39 -> 52
    #
    # ISO years containing week 53 are handled explicitly.
    # --------------------------------------------------------------

    weeks_in_start_year = pd.to_datetime(
        season_start_year
        .astype("Int64")
        .astype("string")
        + "-12-28",
        errors="coerce",
    ).dt.isocalendar()["week"]

    season_week = (
        epiweek - 39
    )

    next_calendar_year = (
        iso_year > season_start_year
    )

    season_week = season_week.where(
        ~next_calendar_year,
        (weeks_in_start_year - 39) + epiweek,
    )

    metadata[
        MASTER.SEASON_WEEK
    ] = (
        season_week.astype("Int64")
    )

    metadata[
        MASTER.EPIDEMIOLOGICAL_SEASON
    ] = (
        season_start_year
        .astype("Int64")
        .astype("string")
        +
        "-"
        +
        (
            season_end_year % 100
        )
        .astype("Int64")
        .astype("string")
        .str.zfill(2)
    )

    # --------------------------------------------------------------
    # Compact season / epiweek label
    #
    # Examples:
    #
    #   W40_S24-25
    #   W52_S24-25
    #   W01_S24-25
    #   W03_S24-25
    #   W39_S24-25
    # --------------------------------------------------------------

    metadata[
        MASTER.SEASON_EPIWEEK
    ] = (
        "W"
        +
        epiweek
        .astype("Int64")
        .astype("string")
        .str.zfill(2)
        +
        "_S"
        +
        (
            season_start_year % 100
        )
        .astype("Int64")
        .astype("string")
        .str.zfill(2)
        +
        "-"
        +
        (
            season_end_year % 100
        )
        .astype("Int64")
        .astype("string")
        .str.zfill(2)
    )

    # --------------------------------------------------------------
    # Compact custom season / epiweek label
    #
    # The epidemiological year corresponds to the year in which
    # the season ends.
    #
    # Examples:
    #
    #   2021-22 -> S22
    #   2022-23 -> S23
    #   2024-25 -> S25
    #
    # Combined labels:
    #
    #   W46_S22
    #   W02_S22
    #   W50_S25
    #   W02_S25
    # --------------------------------------------------------------

    metadata[
        MASTER.SEASON_EPIWEEK_CUSTOM
    ] = (
        "W"
        +
        epiweek
        .astype("Int64")
        .astype("string")
        .str.zfill(2)
        +
        "_S"
        +
        (
            season_end_year % 100
        )
        .astype("Int64")
        .astype("string")
        .str.zfill(2)
    )

    # --------------------------------------------------------------
    # Parse GISAID location
    # --------------------------------------------------------------

    location = (
        metadata[
            MASTER.LOCATION
        ]
        .fillna("")
        .str.split(
            "/",
            expand=True,
        )
        .apply(
            lambda x:
            x.str.strip()
        )
    )

    metadata[
        MASTER.GISAID_REGION
    ] = (
        location[0]
    )

    metadata[
        MASTER.GISAID_COUNTRY
    ] = (
        location[1]
    )

    metadata[
        MASTER.GISAID_DIVISION
    ] = (
        location[2]
    )

    metadata[
        MASTER.GISAID_SUBDIVISION
    ] = (
        location[3]
    )

    return metadata

###############################################################################
# Merge cluster annotations
###############################################################################

def merge_cluster_annotations(
    master_table,
    cluster_annotations,
):
    """
    Merge genetic cluster annotations into the
    master metadata table.
    """

    # Check all clustered sequences are present
    missing = cluster_annotations.loc[
        ~cluster_annotations[
            MASTER.ACCESSION_ID
        ].isin(
            master_table[
                MASTER.ACCESSION_ID
            ]
        )
    ]

    if not missing.empty:
        raise ValueError(
            f"{len(missing)} sequences from "
            "cluster_annotations.tsv were not "
            "found in the master table."
        )

    if master_table[MASTER.ACCESSION_ID].duplicated().any():
     	raise ValueError(
     		"Duplicate Accession IDs found in master_table."
     	)

    if cluster_annotations[MASTER.ACCESSION_ID].duplicated().any():
    	raise ValueError(
    		"Duplicate Accession IDs found in cluster_annotations."
    	)

    # Keep only clustered sequences
    clustered = master_table.loc[
        master_table[
            MASTER.ACCESSION_ID
        ].isin(
            cluster_annotations[
                MASTER.ACCESSION_ID
            ]
        )
    ].copy()

    # Merge cluster annotations
    clustered = clustered.merge(
        cluster_annotations,
        on=MASTER.ACCESSION_ID,
        how="left",
        validate="one_to_one",
    )

    return clustered

###############################################################################
# Build tree metada table
###############################################################################

def build_phylogeny_metadata(
    master_table,
):
    """
    Build a lightweight metadata table for
    phylogenetic annotation.
    """

    # Metadata columns
    columns = [
        column
        for column in DEFAULT_PHYLOGENY_COLUMNS
        if column in master_table.columns
    ]

    # Cluster columns
    cluster_columns = sorted(
        [
            column
            for column in master_table.columns
            if column.startswith(CLUSTER_PREFIX)
        ]
    )

    # Append cluster columns
    columns.extend(
        cluster_columns,
    )

    # Return annotation table
    return (
        master_table[
            columns
        ]
        .copy()
    )


###############################################################################
# Write output tables
###############################################################################

def write_tables(
    master_table_clustered,
    phylogeny_metadata,
    prefix,
    outdir,
):
    """
    Write output tables.
    """

    # Create output directories
    outdir = Path(outdir)
    outdir.mkdir(
        parents=True,
        exist_ok=True,
    )

    # Master table
    master_table_clustered.to_csv(
    	outdir
    	/
        f"{prefix}_master_table_clustered.tsv",
        sep="\t",
        index=False,
    )

    # Phylogeny annotations
    phylogeny_metadata.to_csv(
    	outdir
    	/
        f"{prefix}_phylogeny_metadata.tsv",
        sep="\t",
        index=False,
    )

    return outdir

###############################################################################
# Print summary
###############################################################################

def print_summary(
    master_table,
    phylogeny_metadata,
    outdir,
):
    """
    Print analysis summary.
    """

    cluster_columns = [
        c
        for c in master_table.columns
        if c.startswith(CLUSTER_PREFIX)
    ]

    print()
    print("=" * 70)
    print("Cluster metadata summary")
    print("=" * 70)
    print()
    print(
        f"{'Samples':35}"
        f"{len(master_table):>10,}"
    )
    print(
        f"{'Metadata columns':35}"
        f"{master_table.shape[1]:>10,}"
    )
    print(
        f"{'Cluster columns':35}"
        f"{len(cluster_columns):>10,}"
    )
    print(
        f"{'Phylogeny annotation columns':35}"
        f"{phylogeny_metadata.shape[1]:>10,}"
    )
    print()
    print(
        f"{'Output directory':35}"
        f"{outdir}"
    )

    print()

###############################################################################
# Main
###############################################################################

def main():

    args = parse_args()

    # Read input tables
    master_table = read_master_table(
        master_table=args.master_table,
    )

    cluster_annotations = read_cluster_annotations(
        cluster_annotations=args.cluster_annotations,
    )

    # Enrich metadata
    master_table = enrich_metadata(
        master_table=master_table,
    )

    # Merge cluster annotations
    master_table_clustered = merge_cluster_annotations(
        master_table=master_table,
        cluster_annotations=cluster_annotations,
    )

    # Build phylogeny annotations
    phylogeny_metadata = build_phylogeny_metadata(
        master_table=master_table_clustered,
    )

    # Write output tables
    outdir = write_tables(
        master_table_clustered=master_table_clustered,
        phylogeny_metadata=phylogeny_metadata,
        prefix=args.prefix,
        outdir=args.outdir,
    )

    # Print summary
    print_summary(
        master_table=master_table_clustered,
        phylogeny_metadata=phylogeny_metadata,
        outdir=outdir,
    )

if __name__ == "__main__":
    main()